//! `cargo xtask v86`: the 32-bit multiboot kernel plus the v86 emulator, packaged
//! as a static site in `target/v86/` that boots Rust Runner OS in the browser.
//! Downloads are pinned and checked by SHA-256, then cached in `target/v86-cache/`.
//! Pass `--smoke` to also boot it headless in Node and check the game runs.
use crate::{Result, base64, target_dir, workspace_root};
use std::{
    env, fs,
    path::{Path, PathBuf},
    process::Command,
};

const TARGET_SPEC: &str = "kernel-v86/i686-runner.json";
const V86_VERSION: &str = "0.5.462";
const V86_TGZ_SHA256: &str = "1384ad8bbe80aa4f6cd43f43bd16ddbd7495931df833f038a27fcdc8b9a31351";
/// v86's `bios/` directory at the last commit that changed it.
const BIOS_COMMIT: &str = "b8a39b11dd2076870699e6cac053556271b9bfab";
const BIOS: [(&str, &str); 2] = [
    ("seabios.bin", "73e3f359102e3a9982c35fce98eb7cd08f18303ac7f1ba6ebfbe6cdc1c244d98"),
    ("vgabios.bin", "a4bc0d80cc3ca028c73dafa8fee396b8d054ce87ebd8abfbd31b06b437607880"),
];

fn run(cmd: &mut Command) -> Result<()> {
    let status = cmd.status().map_err(|e| format!("failed to run {cmd:?}: {e}"))?;
    if status.success() { Ok(()) } else { Err(format!("{cmd:?} failed ({status})")) }
}

fn sha256(path: &Path) -> Result<String> {
    let out = Command::new("sha256sum").arg(path).output().map_err(|e| format!("sha256sum: {e}"))?;
    Ok(String::from_utf8_lossy(&out.stdout).split_whitespace().next().unwrap_or("").to_string())
}

/// Downloads `url` to `dest` unless a file with the right hash is already there.
fn fetch(url: &str, dest: &Path, expected: &str) -> Result<()> {
    if dest.exists() && sha256(dest)? == expected {
        return Ok(());
    }
    println!("v86: downloading {url}");
    run(Command::new("curl").args(["-sSfL", "-o"]).arg(dest).arg(url))?;
    let got = sha256(dest)?;
    if got != expected {
        let _ = fs::remove_file(dest);
        return Err(format!("checksum mismatch for {url}: got {got}, expected {expected}"));
    }
    Ok(())
}

fn build_kernel(features: &[&str]) -> Result<PathBuf> {
    let cargo = env::var("CARGO").unwrap_or_else(|_| "cargo".into());
    run(Command::new(cargo)
        .current_dir(workspace_root())
        .args(["build", "--package", "kernel-v86", "--release", "--target", TARGET_SPEC])
        .args(["-Zbuild-std=core,compiler_builtins", "-Zbuild-std-features=compiler-builtins-mem", "-Zjson-target-spec"])
        .args(["--config", "profile.release.debug=false", "--config", "profile.release.strip=true"])
        .args(["--features", &features.join(",")]))?;
    Ok(target_dir().join("i686-runner/release/kernel-v86"))
}

pub fn build(args: &[String]) -> Result<PathBuf> {
    let features: &[&str] = if args.iter().any(|a| a == "--demo") { &["autoplay"] } else { &[] };
    let kernel = build_kernel(features)?;

    let cache = target_dir().join("v86-cache");
    fs::create_dir_all(&cache).map_err(|e| e.to_string())?;
    let tgz = cache.join(format!("v86-{V86_VERSION}.tgz"));
    fetch(&format!("https://registry.npmjs.org/v86/-/v86-{V86_VERSION}.tgz"), &tgz, V86_TGZ_SHA256)?;
    let pkg = cache.join(format!("v86-{V86_VERSION}"));
    if !pkg.join("package/build/v86.wasm").exists() {
        fs::create_dir_all(&pkg).map_err(|e| e.to_string())?;
        run(Command::new("tar").arg("xzf").arg(&tgz).arg("-C").arg(&pkg))?;
    }
    for (name, hash) in BIOS {
        let url = format!("https://raw.githubusercontent.com/copy/v86/{BIOS_COMMIT}/bios/{name}");
        fetch(&url, &cache.join(name), hash)?;
    }

    let out = target_dir().join("v86");
    fs::create_dir_all(&out).map_err(|e| e.to_string())?;
    let copy = |from: &Path, to: &str| -> Result<()> {
        fs::copy(from, out.join(to)).map(|_| ()).map_err(|e| format!("copying {}: {e}", from.display()))
    };
    copy(&kernel, "rust-runner-os.elf")?;
    copy(&pkg.join("package/build/libv86.js"), "libv86.js")?;
    copy(&pkg.join("package/build/v86.wasm"), "v86.wasm")?;
    copy(&pkg.join("package/LICENSE"), "LICENSE-v86.txt")?;
    for (name, _) in BIOS {
        copy(&cache.join(name), name)?;
    }
    // The boot images also ship base64-encoded inside a script, for hosts that
    // only serve web file types (the page loads this, not the raw files).
    let mut js = String::from("// Generated by `cargo xtask v86`: boot images for the v86 page.\nwindow.RUNNER_IMAGES = {\n");
    for (key, file) in [("bios", "seabios.bin"), ("vga_bios", "vgabios.bin"), ("multiboot", "rust-runner-os.elf")] {
        let bytes = fs::read(out.join(file)).map_err(|e| e.to_string())?;
        js.push_str(&format!("  {key}: \"{}\",\n", base64(&bytes)));
    }
    js.push_str("};\n");
    fs::write(out.join("images.js"), js).map_err(|e| e.to_string())?;

    let page = fs::read_to_string(workspace_root().join("web/v86/boot.html")).map_err(|e| e.to_string())?;
    let html = format!(
        "<!doctype html>\n<html lang=\"en\">\n<head>\n<meta charset=\"utf-8\">\n\
         <meta name=\"viewport\" content=\"width=device-width, initial-scale=1, viewport-fit=cover\">\n\
         </head>\n<body>\n{page}\n</body>\n</html>\n"
    );
    fs::write(out.join("index.html"), html).map_err(|e| e.to_string())?;
    let kib = fs::metadata(out.join("rust-runner-os.elf")).map(|m| m.len() / 1024).unwrap_or(0);
    println!("v86: kernel {kib} KiB, site in {}", out.display());

    if args.iter().any(|a| a == "--smoke") {
        smoke(&pkg.join("package"), &out)?;
    }
    Ok(out)
}

/// Boots the site's kernel in v86 under Node and checks title -> play -> game over.
fn smoke(pkg: &Path, site: &Path) -> Result<()> {
    let script = workspace_root().join("web/v86/smoke.mjs");
    let out = Command::new("node")
        .arg(script)
        .arg(pkg)
        .arg(site)
        .output()
        .map_err(|e| format!("failed to run node (is Node.js installed?): {e}"))?;
    let log = String::from_utf8_lossy(&out.stdout);
    println!("{log}");
    if !out.status.success() {
        return Err(format!("v86 smoke test failed\n{}", String::from_utf8_lossy(&out.stderr)));
    }
    Ok(())
}
